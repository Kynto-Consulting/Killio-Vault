function normalizeField(raw: unknown): FormFieldConfig {
  if (!raw || typeof raw !== 'object') return defaultFieldConfig();
  const r = raw as Record<string, unknown>;
  const allowed: FormFieldType[] = [
    'text',
    'textarea',
    'email',
    'url',
    'tel',
    'number',
    'date',
    'select',
    'radio',
    'checkbox',
  ];
  const type = (typeof r.type === 'string' ? r.type : 'text') as FormFieldType;
  return {
    fieldId:
      typeof r.fieldId === 'string' && r.fieldId.trim().length > 0
        ? slugifyFieldId(r.fieldId)
        : `field_${Math.random().toString(36).slice(2, 7)}`,
    label: typeof r.label === 'string' ? r.label : '',
    type: allowed.includes(type) ? type : 'text',
    placeholder: typeof r.placeholder === 'string' ? r.placeholder : '',
    required: Boolean(r.required),
    options: Array.isArray(r.options)
      ? r.options.filter((o): o is string => typeof o === 'string')
      : [],
  };
}

function FieldBrickEditor({
  field,
  onChange,
  onMoveUp,
  onMoveDown,
  onRemove,
}: {
  field: FieldBrick;
  onChange: (next: FormFieldConfig) => void;
  onMoveUp?: () => void;
  onMoveDown?: () => void;
  onRemove: () => void;
}) {
  const t = useTranslations('formBuilder');
  const config = field.content.formField;
  const [typePickerOpen, setTypePickerOpen] = useState(false);

  const typeLabel: Record<FormFieldType, string> = {
    text: t('typeText'),
    textarea: t('typeTextarea'),
    email: t('typeEmail'),
    url: t('typeUrl'),
    tel: t('typeTel'),
    number: t('typeNumber'),
    date: t('typeDate'),
    select: t('typeSelect'),
    radio: t('typeRadio'),
    checkbox: t('typeCheckbox'),
  };
  const allTypes: FormFieldType[] = [
    'text',
    'textarea',
    'email',
    'url',
    'tel',
    'number',
    'date',
    'select',
    'radio',
    'checkbox',
  ];

  return (
    <View className="rounded-md border border-border/70 bg-secondary/20 p-3 gap-2">
      <View className="flex-row items-center justify-between">
        <Text
          style={{ fontFamily: fonts.semibold }}
          className="text-[10px] uppercase tracking-wider text-muted-foreground"
        >
          {t('fieldBrick')}
        </Text>
        <View className="flex-row items-center gap-2">
          <Text
            style={{ fontFamily: fonts.semibold }}
            className="text-[10px] uppercase tracking-wider text-cyan"
          >
            {config.type}
          </Text>
          {onMoveUp ? (
            <Pressable onPress={onMoveUp} hitSlop={6}>
              <ArrowUp size={13} color={colors.mutedForeground} />
            </Pressable>
          ) : null}
          {onMoveDown ? (
            <Pressable onPress={onMoveDown} hitSlop={6}>
              <ArrowDown size={13} color={colors.mutedForeground} />
            </Pressable>
          ) : null}
          <Pressable onPress={onRemove} hitSlop={6}>
            <Trash2 size={13} color={colors.destructive} />
          </Pressable>
        </View>
      </View>

      <TextInput
        value={config.label ?? ''}
        onChangeText={(v) => onChange({ ...config, label: v })}
        placeholder={t('fieldLabelPlaceholder')}
        placeholderTextColor={colors.mutedForeground}
        style={inputStyle}
      />

      <View className="flex-row gap-2">
        <View style={{ flex: 1 }}>
          <Pressable
            onPress={() => setTypePickerOpen(true)}
            className="flex-row items-center justify-between rounded-md border border-border bg-background px-3 py-2"
          >
            <Text style={{ fontFamily: fonts.medium }} className="text-xs text-foreground">
              {typeLabel[config.type]}
            </Text>
            <ChevronDown size={13} color={colors.mutedForeground} />
          </Pressable>
        </View>
        <View style={{ flex: 1 }}>
          <TextInput
            value={config.placeholder ?? ''}
            onChangeText={(v) => onChange({ ...config, placeholder: v })}
            placeholder={t('fieldPlaceholderPlaceholder')}
            placeholderTextColor={colors.mutedForeground}
            editable={config.type !== 'checkbox' && config.type !== 'radio'}
            style={[
              inputStyle,
              config.type === 'checkbox' || config.type === 'radio' ? { opacity: 0.5 } : null,
            ]}
          />
        </View>
      </View>

      <View className="flex-row items-center justify-between">
        <View className="flex-row items-center gap-2">
          <Switch
            value={!!config.required}
            onValueChange={(v) => onChange({ ...config, required: v })}
            trackColor={{ false: '#2a2a2a', true: colors.cyan }}
          />
          <Text style={{ fontFamily: fonts.medium }} className="text-xs text-foreground">
            {t('required')}
          </Text>
        </View>
        <Text
          style={{ fontFamily: fonts.mono }}
          className="text-[10px] text-muted-foreground"
          numberOfLines={1}
        >
          {config.fieldId}
        </Text>
      </View>

      {config.type === 'select' || config.type === 'radio' ? (
        <TextInput
          value={(config.options ?? []).join(', ')}
          onChangeText={(v) =>
            onChange({
              ...config,
              options: v
                .split(',')
                .map((o) => o.trim())
                .filter(Boolean),
            })
          }
          placeholder={t('optionsPlaceholder')}
          placeholderTextColor={colors.mutedForeground}
          style={inputStyle}
        />
      ) : null}

      <Modal
        visible={typePickerOpen}
        transparent
        animationType="fade"
        onRequestClose={() => setTypePickerOpen(false)}
      >
        <Pressable
          onPress={() => setTypePickerOpen(false)}
          className="flex-1 items-center justify-end bg-background/80"
        >
          <View className="w-full rounded-t-2xl border-t border-border bg-card p-4 gap-2">
            <Text style={{ fontFamily: fonts.bold }} className="text-base text-foreground">
              {t('fieldKey')}
            </Text>
            {allTypes.map((tp) => (
              <Pressable
                key={tp}
                onPress={() => {
                  onChange({ ...config, type: tp });
                  setTypePickerOpen(false);
                }}
                className={`rounded-md border border-border bg-background px-3 py-2 ${
                  tp === config.type ? 'border-cyan' : ''
                }`}
              >
                <Text style={{ fontFamily: fonts.medium }} className="text-sm text-foreground">
                  {typeLabel[tp]}
                </Text>
              </Pressable>
            ))}
          </View>
        </Pressable>
      </Modal>
    </View>
  );
}

function FieldBrickViewer({
  field,
  value,
  onChange,
}: {
  field: FieldBrick;
  value: string | boolean | undefined;
  onChange: (v: string | boolean) => void;
}) {
  const config = field.content.formField;
  const label = config.label || config.fieldId;
  if (config.type === 'checkbox') {
    return (
      <View className="flex-row items-center gap-2">
        <Switch
          value={value === true}
          onValueChange={onChange}
          trackColor={{ false: '#2a2a2a', true: colors.cyan }}
        />
        <Text style={{ fontFamily: fonts.medium }} className="text-sm text-foreground">
          {label}
          {config.required ? ' *' : ''}
        </Text>
      </View>
    );
  }
  if (config.type === 'select' || config.type === 'radio') {
    const opts = config.options ?? [];
    return (
      <View className="gap-1">
        <Text style={{ fontFamily: fonts.medium }} className="text-xs text-foreground">
          {label}
          {config.required ? ' *' : ''}
        </Text>
        <View className="flex-row flex-wrap gap-1">
          {opts.map((opt) => {
            const selected = typeof value === 'string' && value === opt;
            return (
              <Pressable
                key={opt}
                onPress={() => onChange(opt)}
                className={`rounded-md border px-2 py-1 ${
                  selected ? 'border-cyan bg-cyan/10' : 'border-border bg-background'
                }`}
              >
                <Text style={{ fontFamily: fonts.medium }} className="text-[11px] text-foreground">
                  {opt}
                </Text>
              </Pressable>
            );
          })}
        </View>
      </View>
    );
  }
  return (
    <View className="gap-1">
      <Text style={{ fontFamily: fonts.medium }} className="text-xs text-foreground">
        {label}
        {config.required ? ' *' : ''}
      </Text>
      <TextInput
        value={typeof value === 'string' ? value : ''}
        onChangeText={onChange}
        placeholder={config.placeholder ?? ''}
        placeholderTextColor={colors.mutedForeground}
        multiline={config.type === 'textarea'}
        keyboardType={
          config.type === 'number'
            ? 'numeric'
            : config.type === 'email'
              ? 'email-address'
              : config.type === 'tel'
                ? 'phone-pad'
                : config.type === 'url'
                  ? 'url'
                  : 'default'
        }
        autoCapitalize={config.type === 'email' || config.type === 'url' ? 'none' : 'sentences'}
        style={inputStyle}
      />
    </View>
  );
}
